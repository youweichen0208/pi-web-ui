import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {setTimeout as sleep} from 'node:timers/promises';
import {chromium} from 'playwright-core';
import {CHROME_PATH} from './lib/chrome.mjs';
import {portUp} from './lib/port-utils.mjs';
const base=mkdtempSync(join(tmpdir(),'pi-highlight-'));
const port=8995;
writeFileSync(join(base,'note.md'),'# Highlight test\n\nOriginal paragraph.\n');
let server,browser;
try {
	assert.equal(await portUp(port),false);
	server=spawn(process.execPath,['dist/server/index.js'],{env:{...process.env,PORT:String(port),PI_WEB_CWD:base,PI_WEB_DATA_DIR:join(base,'data'),PI_CODING_AGENT_DIR:join(base,'agent')},stdio:'ignore'});
	for(let i=0;i<100&&!await portUp(port);i++) await sleep(100);
	browser=await chromium.launch({executablePath:CHROME_PATH});
	const page=await browser.newPage({viewport:{width:1440,height:950}});
	await page.goto(`http://localhost:${port}`);
	await page.locator('.setup-modal .modal-close').click();
	await page.locator('.file-name',{hasText:'note.md'}).click();
	const editRich=async()=>{await page.locator('.fp-more').evaluate(e=>e.open=true);await page.locator('.fp-more-actions').getByRole('button',{name:'编辑文件'}).click();};
	await editRich();
	const editor=page.locator('.fp-rich-document');
	await editor.locator('p').first().evaluate(element=>{
		const range=document.createRange();range.selectNodeContents(element);
		const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range);
	});
	await page.getByRole('toolbar',{name:'文档格式'}).getByRole('button',{name:'粗体',exact:true}).click();
	assert.equal(await editor.locator('strong, b').first().innerText(),'Original paragraph.');
	await editor.click();
	await page.keyboard.press('ControlOrMeta+End');
	await page.keyboard.press('Enter');
	await page.keyboard.type('/highlight');
	await page.getByRole('option',{name:'高亮块',exact:true}).click();
	const highlight=editor.locator('blockquote.rich-highlight');
	await highlight.waitFor();
	assert.equal(await highlight.evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(222, 236, 255)');
	await page.keyboard.insertText('举个例子：这是高亮内容。');
	assert.match(await highlight.innerText(),/举个例子/);
	const save=async()=>{
		await page.locator('.fp-header-save').click();
		await page.waitForFunction(()=>document.querySelector('.fp-header-status')?.textContent?.includes('已保存'));
	};
	await save();
	let saved=readFileSync(join(base,'note.md'),'utf8');
	assert(saved.includes('> [!NOTE]'),saved);
	assert(saved.includes('**Original paragraph.**'),saved);
	assert(saved.includes('> 举个例子：这是高亮内容。'),saved);
	assert(!saved.includes('data-rich-'),saved);
	await page.locator('.fp-back').click();
	await page.locator('.file-name',{hasText:'note.md'}).click();
	await editRich();
	await highlight.waitFor();
	assert.match(await highlight.innerText(),/举个例子/);
	await highlight.locator('p').fill('修改后的高亮内容');
	await save();
	saved=readFileSync(join(base,'note.md'),'utf8');
	assert(saved.includes('> 修改后的高亮内容'),saved);
	assert.equal((saved.match(/\[!NOTE\]/g)||[]).length,1);
	await page.getByRole('button',{name:'源码',exact:true}).click();
	assert.match(await page.locator('.fp-editor').inputValue(),/> \[!NOTE\]/);
	await editRich();
	await highlight.waitFor();
	console.log('PASS highlight insertion, light styling, Markdown save/reopen, editing and source round-trip');
} finally {
	await browser?.close();
	server?.kill('SIGTERM');
}
