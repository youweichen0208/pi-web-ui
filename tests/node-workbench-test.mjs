import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { startMockSsh } from "./lib/mock-ssh.mjs";
import { NodeWorkbench } from "../dist/server/node-workbench.js";
import { PluginSecrets } from "../dist/server/plugin-facilities.js";

const dataDir = mkdtempSync(join(tmpdir(), "pi-node-test-"));
const port = 8938;
const mock = await startMockSsh(process.cwd(), port);
const service = new NodeWorkbench(dataDir);
const events = [];
const detach = service.attach("client-a", (event) => events.push(event));
async function call(action, nodeId, payload = {}, terminalId, conversationId) {
	const requestId = crypto.randomUUID();
	await service.handle("client-a", { type: "node_request", requestId, action, nodeId, terminalId, conversationId, payload });
	const response = events.findLast((e) => e.requestId === requestId && (e.event === "result" || e.event === "failure"));
	assert(response, `${action}: missing response`);
	return response;
}
try {
	const saved = await call("save", undefined, { name: "alpha", group: "prod", host: "127.0.0.1", port, username: "tester", auth: "password", secret: "secret123", defaultDir: "/home/test" });
	const nodeId = saved.data.id;
	assert.equal(readFileSync(join(dataDir, "nodes.json"), "utf8").includes("secret123"), false);
	PluginSecrets.keys.clear();
	assert.equal(new PluginSecrets(dataDir, join(dataDir, "node-workbench")).get(`node:${nodeId}:secret`), "secret123");
	const first = await call("connect", nodeId);
	assert.equal(first.event, "failure");
	const trust = events.findLast((e) => e.event === "trust_required" && e.nodeId === nodeId);
	assert.match(trust.data.fingerprint, /^SHA256:/);
	assert.equal((await call("trust", nodeId, { fingerprint: trust.data.fingerprint })).event, "result");
	const concurrent = await Promise.all([call("connect", nodeId), call("connect", nodeId)]);
	assert.equal(concurrent.filter((response) => response.event === "result").length, 1);
	assert.equal(service.connections.size, 1);
	assert.equal((await call("save", undefined, { id: nodeId, name: "alpha", group: "prod", host: "127.0.0.1", port, username: "tester", auth: "key", keyPath: "", defaultDir: "/" })).event, "failure");
	assert.equal(service.connections.size, 1);
	const opened = await call("terminal_open", nodeId, {}, "term-a");
	assert.equal(opened.event, "result");
	const conversationId = opened.data.conversationId;
	const chatState = await call("chat_state", nodeId);
	assert.equal(chatState.event, "result");
	assert.equal(chatState.data.conversationId, conversationId);
	assert.deepEqual(service.chats.get(JSON.stringify(["client-a", nodeId])).session.getActiveToolNames().sort(), ["remote_command", "remote_read", "remote_write"]);
	assert.equal((await call("terminal_input", nodeId, { data: "hello\r" }, "term-a", conversationId)).event, "result");
	await new Promise((r) => setTimeout(r, 50));
	assert(events.some((e) => e.event === "terminal_output" && e.nodeId === nodeId && e.terminalId === "term-a" && e.data.text.includes("echo:hello")));
	const output = await service.execute("client-a", nodeId, "term-a", "pwd");
	assert.match(output, /echo:pwd/);
	assert(events.some((e) => e.event === "terminal_output" && e.nodeId === nodeId && e.terminalId === "term-a" && e.data.text.includes("echo:pwd")));
	const truncated = await service.execute("client-a", nodeId, "term-a", "x".repeat(70000));
	assert(truncated.includes("[输出已截断]"));
	assert(truncated.length < 66000);
	const secondTerminal = await call("terminal_open", nodeId, {}, "term-b", conversationId);
	assert.equal(secondTerminal.event, "result");
	await call("terminal_select", nodeId, {}, "term-b", conversationId);
	const remoteCommand = service.chats.get(JSON.stringify(["client-a", nodeId])).session.getToolDefinition("remote_command");
	const before = events.length;
	const toolResult = await remoteCommand.execute("tool-test", { command: "whoami" });
	assert.match(toolResult.content[0].text, /echo:whoami/);
	assert(events.slice(before).some((e) => e.event === "terminal_output" && e.terminalId === "term-b" && e.data.text.includes("echo:whoami")));
	assert(!events.slice(before).some((e) => e.event === "terminal_output" && e.terminalId === "term-a" && e.data.text.includes("echo:whoami")));
	await call("terminal_open", nodeId, {}, "term-trap", conversationId);
	await call("terminal_input", nodeId, { data: "trap_foreground\r" }, "term-trap", conversationId);
	await assert.rejects(service.execute("client-a", nodeId, "term-trap", "must_not_run"), /无法确认 shell 提示符/);
	assert(!events.some((e) => e.event === "terminal_output" && e.terminalId === "term-trap" && e.data.text.includes("must_not_run")));
	const interrupted = service.execute("client-a", nodeId, "term-trap", "still_not_run");
	await new Promise((r) => setTimeout(r, 30));
	await call("interrupt", nodeId, {}, "term-trap", conversationId);
	await assert.rejects(interrupted, /命令已中断/);
	assert.equal((await call("read", nodeId, { path: "/home/test/a.txt" })).data.text, "hello ssh\n第二行\n");
	assert.equal((await call("write", nodeId, { path: "/home/test/new.txt", text: "node write" })).event, "result");
	assert.equal((await call("read", nodeId, { path: "/home/test/new.txt" })).data.text, "node write");
	assert.equal((await call("terminal_input", "wrong-node", { data: "oops" }, "term-a", conversationId)).event, "failure");
	service.nodes.find((n) => n.id === nodeId).fingerprint = "SHA256:changed";
	assert.equal((await call("connect", nodeId)).event, "failure");
	service.nodes.find((n) => n.id === nodeId).fingerprint = trust.data.fingerprint;
	assert.equal((await call("connect", nodeId)).event, "result");
	const wrong = await call("save", undefined, { name: "bad", group: "test", host: "127.0.0.1", port, username: "tester", auth: "password", secret: "wrong", defaultDir: "/" });
	const wrongId = wrong.data.id;
	assert.equal((await call("trust", wrongId, { fingerprint: trust.data.fingerprint })).event, "failure");
	assert.equal((await call("export")).data.nodes.some((n) => "secret" in n), false);
	const eventsB = [];
	const detachB = service.attach("client-b", (event) => eventsB.push(event));
	await service.handle("client-b", { type: "node_request", requestId: "b-connect", action: "connect", nodeId });
	assert.equal(eventsB.findLast((e) => e.requestId === "b-connect")?.event, "result");
	assert.equal((await call("delete", nodeId)).event, "result");
	assert(![...service.connections.values()].some((connection) => connection.nodeId === nodeId));
	detachB();
	console.log("✓ SSH trust, key change, authentication, terminal command/interrupt/truncation, SFTP and node isolation");
} finally {
	for (const c of [...service.connections.values()]) await call("disconnect", c.nodeId);
	detach(); mock.close(); rmSync(dataDir, { recursive: true, force: true });
}
