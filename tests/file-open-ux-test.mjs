/** File-open workflow: explicit references, compact header, source/diff and external edits. */
import assert from "node:assert/strict";
import { spawn, execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { setTimeout as sleep } from "node:timers/promises";
import { chromium } from "playwright-core";
import { CHROME_PATH } from "./lib/chrome.mjs";
import { portUp } from "./lib/port-utils.mjs";

const port = 8992;
const cwd = mkdtempSync(join(tmpdir(), "file-open-ux-"));
const path = join(cwd, "note.md");
writeFileSync(path, "# Heading\n\nAlpha `beta`.\n");
writeFileSync(join(cwd, "code.ts"), "export const value = 1;\n");
execFileSync("git", ["init", "-q"], { cwd });
execFileSync("git", ["add", "code.ts"], { cwd });
execFileSync("git", ["-c", "user.name=Test", "-c", "user.email=test@example.com", "commit", "-qm", "initial"], { cwd });
writeFileSync(join(cwd, "code.ts"), "export const value = 2;\nexport const extra = true;\n");
let server;
let browser;
try {
	assert.equal(await portUp(port), false);
	server = spawn(process.execPath, ["dist/server/index.js"], { env: { ...process.env, PORT: String(port), PI_WEB_CWD: cwd, PI_WEB_DATA_DIR: join(cwd, "data"), PI_CODING_AGENT_DIR: join(cwd, "agent") }, stdio: ["ignore", "pipe", "pipe"] });
	let serverOutput = "";
	server.stderr.on("data", (chunk) => { serverOutput += chunk; });
	for (let i = 0; i < 100 && !await portUp(port); i++) await sleep(100);
	assert(await portUp(port), serverOutput);
	browser = await chromium.launch({ executablePath: CHROME_PATH });
	const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
	await page.goto(`http://localhost:${port}`);
	await page.locator(".setup-modal .modal-close").click();
	await page.locator(".file-name", { hasText: "note.md" }).click();
	await page.locator(".fp-markdown h1").waitFor();
	assert.equal(await page.locator(".fp-rich-document").getAttribute("contenteditable"), "true");
	assert.equal(await page.locator(".attach-chip.reference").count(), 1, "opening a file should attach a path reference");
	const header = await page.locator(".fp-title-row").boundingBox();
	assert(header.height < 58, `header should occupy one row: ${header.height}`);
	assert.equal(await page.locator(".fp-foot").count(), 0);
	assert.equal(await page.locator(".fp-markdown h1").evaluate((node) => Math.round(parseFloat(getComputedStyle(node).fontSize))), 27);
	await page.screenshot({ path: "/private/tmp/pi-file-open-ux.png" });
	await page.locator(".fp-reference").click();
	assert.equal(await page.locator(".attach-chip.reference").count(), 1, "explicit reference should not duplicate the automatic one");
	await page.locator(".attach-chip.reference button").click();
	await page.locator(".fp-markdown p", { hasText: "Alpha beta." }).evaluate((node) => {
		const range = document.createRange();
		range.selectNodeContents(node);
		const selected = window.getSelection();
		selected.removeAllRanges();
		selected.addRange(range);
		node.dispatchEvent(new MouseEvent("mouseup", { bubbles: true }));
	});
	const quote = await page.locator(".fp-quote-selection").boundingBox();
	const quoteStyle = await page.locator(".fp-quote-selection").evaluate((node) => { const style = getComputedStyle(node); return { position: style.position, left: style.left, right: style.right, top: style.top, bottom: style.bottom }; });
	assert(quote && quote.width < 360 && quote.height < 64, `selection quote must stay a compact button: ${JSON.stringify({ quote, quoteStyle })}`);
	await page.locator(".fp-quote-selection").click();
	await page.locator(".attach-chip.lines").waitFor();
	assert.match(await page.locator(".attach-chip.lines").textContent(), /note\.md.*3/);
	await page.locator(".fp-rich-document h1").click();
	await page.keyboard.press("End");
	await page.keyboard.type(" updated");
	await page.locator(".fp-header-save").waitFor();
	assert.equal(readFileSync(path, "utf8"), "# Heading\n\nAlpha `beta`.\n", "preview edits should remain drafts until saved");
	await page.locator(".fp-header-save").click();
	await page.waitForFunction(() => document.querySelector(".fp-header-status")?.textContent?.includes("已保存"));
	assert.match(readFileSync(path, "utf8"), /Heading updated/, "save should write preview edits to disk");
	await page.getByRole("button", { name: "源码", exact: true }).click();
	await page.locator(".fp-editor").waitFor();
	await page.locator(".fp-editor").fill("# Heading\n\nLocal draft.\n");
	await page.locator(".fp-header-save").waitFor();
	await page.locator(".fp-editor").press("ArrowUp");
	await page.locator(".fp-editor").press("Home");
	await page.locator(".fp-editor").press("Shift+End");
	await page.locator(".fp-quote-selection").waitFor();
	writeFileSync(path, "# Heading\n\nChanged by pi.\n");
	await page.locator(".fp-external-banner").waitFor({ timeout: 10000 });
	await page.locator(".fp-external-banner").getByRole("button", { name: "对比" }).click();
	await page.locator(".fp-external-comparison").waitFor();
	assert.match(await page.locator(".fp-external-comparison").textContent(), /Local draft/);
	assert.match(await page.locator(".fp-external-comparison").textContent(), /Changed by pi/);
	await page.getByRole("button", { name: "源码", exact: true }).click();
	await page.locator(".fp-header-action", { hasText: "改动 1" }).click();
	await page.locator(".fp-diff-view pre").waitFor();
	assert.match(await page.locator(".fp-diff-view pre").textContent(), /Changed by pi/);
	const handle = await page.locator(".view-pane:not(.hidden) .resize-right").boundingBox();
	await page.mouse.move(handle.x + handle.width / 2, handle.y + 120);
	await page.mouse.down();
	await page.mouse.move(handle.x - 80, handle.y + 120);
	await page.mouse.up();
	const savedShare = await page.evaluate(() => Number(localStorage.getItem("pi-web-ui:editor-share")));
	assert(savedShare > 0.45 && savedShare < 0.7);
	await page.locator(".fp-back").click();
	await page.locator(".fp-leave").getByRole("button", { name: "放弃修改" }).click();
	await page.reload();
	await page.locator(".setup-modal .modal-close").click();
	await page.locator(".file-name", { hasText: "note.md" }).click();
	await page.locator(".fp-markdown h1").waitFor();
	const restoredShare = await page.evaluate(() => {
		const pane = document.querySelector(".view-pane:not(.hidden)");
		const chat = pane.querySelector(".main").getBoundingClientRect().width;
		const editor = pane.querySelector(".drawer-right").getBoundingClientRect().width;
		return editor / (chat + editor);
	});
	assert(Math.abs(restoredShare - savedShare) < 0.005);
	await page.locator(".fp-back").click();
	await page.locator(".file-name", { hasText: "code.ts" }).click();
	await page.locator(".fp-code-editor").waitFor();
	assert.equal(await page.locator(".fp-embedded").getAttribute("data-code-theme"), "light");
	assert(await page.locator(".fp-code-editor").evaluate((node) => getComputedStyle(node).backgroundColor) !== "rgb(31, 29, 26)");
	assert.equal(await page.locator(".fp-code-editor").evaluate((node) => node.classList.contains("no-wrap")), true);
	await page.locator(".fp-edit-marker.changed").first().waitFor();
	await page.locator(".fp-edit-marker.added").first().waitFor();
	await page.screenshot({ path: "/private/tmp/pi-code-file-ux.png" });
	await page.locator(".fp-header-action", { hasText: "改动 1" }).click();
	await page.locator(".fp-diff-view").waitFor();
	await page.getByRole("button", { name: "编辑", exact: true }).click();
	await page.locator(".fp-editor").waitFor();
	await page.getByRole("button", { name: "只读", exact: true }).click();
	await page.locator(".fp-code").waitFor();
	await page.locator(".fp-more summary").click();
	await page.getByRole("button", { name: "开启自动换行" }).click();
	assert.equal(await page.locator(".fp-code").evaluate((node) => node.classList.contains("no-wrap")), false);
	assert(await page.locator(".fp-code-text").first().evaluate((node) => parseFloat(getComputedStyle(node).textIndent)) < 0);
	await page.locator("#sidebar-settings-slot button:visible").click();
	await page.locator("#sidebar-settings-slot .dd-item", { hasText: "设置" }).click();
	await page.locator(".settings-tab", { hasText: "外观" }).click();
	await page.locator("#settings-code-theme").selectOption("dark");
	assert.equal(await page.locator(".fp-embedded").getAttribute("data-code-theme"), "dark");
	await page.locator("#settings-code-theme").selectOption("light");
	await page.locator(".settings-modal .modal-close").click();
	console.log("PASS file-open UX: header, references, source, diff markers, code theme, wrap, external change banner");
} finally {
	await browser?.close();
	server?.kill("SIGTERM");
}
